check($plan['groups'][$travelKey]['name'] === 'Travel' && $plan['targets'][$travelKey] === 0 && $plan['targets']['misc'] === 100000, 'starting a fund separates Travel from Misc without inventing a contribution');
rejects(fn() => start_travel_fund($db, 35, $month, '400', budget_form_version($plan)), 'opening savings cannot be added a second time');
check(travel_fund_balance($db, 36, $month) === null, 'travel balances are isolated by user');
