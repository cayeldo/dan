save_import($db, 35, pending_csv("Date,Name,Amount\n$month-01,COSTCO,-1250\n"));
$balance = travel_fund_balance($db, 35, $month);
check($balance['available_cents'] === 35000 && $balance['reallocated_cents'] === 25000 && $balance['reserve_used_elsewhere_cents'] === 5000, 'recorded purchases draw from current contribution and then saved funds');
$progress = budget_progress($db, 35, $month);
check($progress['groups'][$travelKey]['available_cents'] === 35000 && array_sum(array_column($progress['groups'], 'available_cents')) === $progress['total']['available_cents'], 'displayed category availability accounts for transferred travel funds and reconciles');
